CHARS = ''.join(G.keys())


def base(rows):
    """rejilla de 8x8 (True = pixel)"""
    g = [[False] * 8 for _ in range(8)]
    for y, r in enumerate(rows[:8]):
        for x, ch in enumerate(r[:8]):
            g[y][x] = ch == '#'
    return g


def scale2x(g):
    """Scale2x (EPX): cada pixel pasa a 2x2 y las esquinas siguen a los vecinos, asi las diagonales salen redondeadas"""
    n = len(g)
    out = [[False] * (n * 2) for _ in range(n * 2)]
    at = lambda x, y: g[y][x] if 0 <= x < n and 0 <= y < n else False
    for y in range(n):
        for x in range(n):
            p, a, b, c, d = at(x, y), at(x, y - 1), at(x + 1, y), at(x - 1, y), at(x, y + 1)
            e0 = a if (c == a and c != d and a != b) else p
            e1 = b if (a == b and a != c and b != d) else p
            e2 = c if (d == c and d != b and c != a) else p
            e3 = d if (b == d and b != a and d != c) else p
            out[2 * y][2 * x], out[2 * y][2 * x + 1], out[2 * y + 1][2 * x], out[2 * y + 1][2 * x + 1] = e0, e1, e2, e3
    return out


def font(fid='f_pixel16', name='Pixel 16'):
    """fuente de pixeles del proyecto (formato de doc["fonts"])"""
    glyphs = []
    for c in CHARS:
        g = scale2x(base(G[c]))
        glyphs.append({'pixels': ['#ffffff' if g[y][x] else '' for y in range(16) for x in range(16)]})
    return {'id': fid, 'name': name, 'kind': 'pixel', 'cellW': 16, 'cellH': 16, 'chars': CHARS, 'glyphs': glyphs,
            'spacing': 2, 'mono': False, 'tint': True}


def preview(path, text='AJEDREZ ¡Jaque mate! Juegan las blancas 1. e4 Cc6 2. Dh4# exd5+ Fácil, Difícil… Menú ¿Revancha?'):
    from PIL import Image
    f = font()
    idx = {c: i for i, c in enumerate(CHARS)}
    S = 2
    lines, line, width = [], '', 60
    for w in text.split(' '):
        if len(line) + len(w) + 1 > width:
            lines.append(line); line = w
        else:
            line = (line + ' ' + w).strip()
    lines.append(line)
    img = Image.new('RGB', (width * 12 * S, len(lines) * 20 * S), (32, 35, 43))
    for li, ln in enumerate(lines):
        x = 4
        for ch in ln:
            gl = f['glyphs'][idx[ch]]['pixels']
            right = max([xx for yy in range(16) for xx in range(16) if gl[yy * 16 + xx]] or [7])
            for yy in range(16):
                for xx in range(16):
                    if gl[yy * 16 + xx]:
                        for dy in range(S):
                            for dx in range(S):
                                img.putpixel(((x + xx) * S + dx, (li * 20 + 2 + yy) * S + dy), (240, 230, 210))
            x += right + 1 + 2
    img.save(path)


